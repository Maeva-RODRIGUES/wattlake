"""Pin the ingestion dependencies that the Airflow constraints leave free.

The image and the tests install the ingestion package with the constraints of
Airflow 3.2.2, which pin most of its dependencies. The few they do not list
(PyIceberg's own dependencies, for example) would take whatever version is
latest at build time: ingestion/constraints.txt pins them.

Usage (through the Makefile):
  filter: keep, from a full "uv pip compile" output, only the packages absent
          from the Airflow constraints (make ingestion-lock).
  check:  fail if an installed package is pinned by neither file
          (make ingestion-lock-check, run in CI).
"""

import argparse
import re
import sys
from pathlib import Path


def normalize(name: str) -> str:
    """Package name as PyPI compares them (PEP 503): case and separators ignored."""
    return re.sub(r"[-_.]+", "-", name).lower()


def pins(path: Path) -> dict[str, str]:
    """Return {normalized name: line} for every "name==version" line of a requirements file."""
    result = {}
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if "==" in line:
            result[normalize(line.split("==", 1)[0])] = line
    return result


HEADER = """\
# Ingestion dependencies absent from the Airflow constraints, pinned here.
# Applied with the Airflow constraints by ingestion/Dockerfile and the Makefile.
# Generated by "make ingestion-lock" (tools/ingestion_constraints.py), ignoring
# releases newer than {exclude_newer}: do not edit by hand.
"""


def filter_pins(compiled: Path, airflow: Path, output: Path, exclude_newer: str) -> None:
    covered = pins(airflow)
    extra = sorted(line for name, line in pins(compiled).items() if name not in covered)
    output.write_text(HEADER.format(exclude_newer=exclude_newer) + "".join(f"{line}\n" for line in extra))
    print(f"{output}: {len(extra)} packages pinned outside the Airflow constraints")


def check(freeze: Path, airflow: Path, local: Path) -> int:
    covered = pins(airflow) | pins(local)
    # The ingestion package itself is frozen as "-e file://..." or "... @ file://...",
    # without "==": pins() leaves it out.
    uncovered = [line for name, line in pins(freeze).items() if name not in covered]
    if uncovered:
        print(f"Installed but pinned by neither the Airflow constraints nor {local}:")
        print("\n".join(f"  {line}" for line in uncovered))
        print("Fix: make ingestion-lock, then review and commit the result.")
        return 1
    print(f"Every installed package is pinned by the Airflow constraints or {local}.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)

    filter_cmd = commands.add_parser("filter")
    filter_cmd.add_argument("--compiled", type=Path, required=True)
    filter_cmd.add_argument("--airflow", type=Path, required=True)
    filter_cmd.add_argument("--output", type=Path, required=True)
    filter_cmd.add_argument("--exclude-newer", required=True, help="date passed to uv, recorded in the header")

    check_cmd = commands.add_parser("check")
    check_cmd.add_argument("--freeze", type=Path, required=True, help="output of pip freeze")
    check_cmd.add_argument("--airflow", type=Path, required=True)
    check_cmd.add_argument("--local", type=Path, required=True)

    args = parser.parse_args()
    if args.command == "filter":
        filter_pins(args.compiled, args.airflow, args.output, args.exclude_newer)
        return 0
    return check(args.freeze, args.airflow, args.local)


if __name__ == "__main__":
    sys.exit(main())
